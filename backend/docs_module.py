# ---------- PDF renderers (per doc type) ----------

def _render_common(doc: dict, title: str, subtitle: str, body_html: str, footer: str) -> str:
    ref = _esc(doc.get("reference", "") or doc.get("doc_id", ""))
    now_str = datetime.now(timezone.utc).strftime("%d %b %Y")
    return f"""<!doctype html><html><head><meta charset="utf-8"><title>{_esc(title)}</title>
<style>{_common_css()}</style></head>
<body data-footer="{_esc(doc.get('company_name',''))} · {ref} · {footer}">
{_header(title, subtitle, ref, now_str)}
{_legal_box()}
{body_html}
{_footer_note(title)}
</body></html>"""


def _kv(items: list[tuple[str, Any]]) -> str:
    rows = "".join(
        f"<tr><td class='k'>{_esc(k)}</td><td>{_esc(v) if v is not None else '—'}</td></tr>"
        for k, v in items
    )
    return f'<table class="kv"><tbody>{rows}</tbody></table>'


def _section(title: str, inner: str) -> str:
    return f"<h2>{_esc(title)}</h2>{inner}"


# ========== JSA ==========
def render_jsa(doc: dict) -> str:
    steps = doc.get("steps") or []
    rows = ""
    for i, s in enumerate(steps):
        hz = "<ul>" + "".join(f"<li>{_esc(h)}</li>" for h in s.get('hazards', []) if h) + "</ul>"
        ctrl = "<ul>" + "".join(f"<li>{_esc(c)}</li>" for c in s.get('controls', []) if c) + "</ul>"
        rows += f"<tr><td>{i+1}. {_esc(s.get('step',''))}</td><td>{hz}</td><td>{ctrl}</td></tr>"
    body = (
        _section("Job details", _kv([
            ("Task", doc.get("task")), ("Site", doc.get("site")),
            ("Date", doc.get("work_date")), ("Prepared by", doc.get("prepared_by")),
            ("Workers", ", ".join(doc.get("worker_names", []) or [])),
        ]))
        + _section("Steps, Hazards and Controls",
                   f"<table><thead><tr><th>Step</th><th>Hazards</th><th>Controls</th></tr></thead>"
                   f"<tbody>{rows or '<tr><td colspan=3>—</td></tr>'}</tbody></table>")
        + _section("PPE Required", "<div>" + "".join(
            f'<div class="ck"><span class="mono">☒</span> {_esc(p)}</div>'
            for p in (doc.get("ppe") or [])) + "</div>")
        + _section("Note",
                   "<p style='font-size:9pt;color:#666;'>A JSA is NOT a substitute for a SWMS where "
                   "High Risk Construction Work is involved. Use SafeTradie's SWMS Generator for HRCW.</p>")
    )
    return _render_common(doc, "Job Safety Analysis", "Hazard identification for non-HRCW tasks",
                          body, "Job Safety Analysis")


# ========== Risk Assessment ==========
def render_risk_assessment(doc: dict) -> str:
    items = doc.get("items") or []
    rows = ""
    for i, it in enumerate(items):
        inh = (it.get("inherent_likelihood", 0)) * (it.get("inherent_consequence", 0))
        res = (it.get("residual_likelihood", 0)) * (it.get("residual_consequence", 0))
        rows += (f"<tr><td>{i+1}. {_esc(it.get('hazard',''))}</td>"
                 f"<td>{inh}<br><small>({it.get('inherent_likelihood','')}×{it.get('inherent_consequence','')})</small></td>"
                 f"<td>{_esc(it.get('controls',''))}</td>"
                 f"<td>{res}<br><small>({it.get('residual_likelihood','')}×{it.get('residual_consequence','')})</small></td>"
                 f"<td>{_esc(it.get('responsible',''))}</td></tr>")
    body = (
        _section("Activity details", _kv([
            ("Activity", doc.get("activity")), ("Site", doc.get("site")),
            ("Trade", doc.get("trade")), ("Prepared by", doc.get("prepared_by")),
            ("Review date", doc.get("review_date")),
        ]))
        + _section("Risk register",
                   "<table><thead><tr><th>Hazard</th><th>Inherent</th><th>Controls</th>"
                   "<th>Residual</th><th>Responsible</th></tr></thead>"
                   f"<tbody>{rows or '<tr><td colspan=5>—</td></tr>'}</tbody></table>")
    )
    return _render_common(doc, "Risk Assessment",
                          "Activity risk identification and controls",
                          body, "Risk Assessment")


