import SwmsPreview from "./SwmsPreview";

const STEPS = [
  { key: "business", label: "1. Business & Job" },
  { key: "trade", label: "2. Trade & Activity" },
  { key: "hrcw", label: "3. HRCW Categories" },
  { key: "rows", label: "4. Tasks / Hazards / Controls" },
  { key: "compliance", label: "5. Compliance & Review" },
  { key: "equipment", label: "6. Equipment / PPE / Training" },
  { key: "signoff", label: "7. Generate & Sign" },
];

const SITE_TYPES = [
  "Residential — house or townhouse construction",
  "Residential — renovation or alteration",
  "Commercial — new construction",
  "Commercial — renovation or fitout",
  "Industrial",
  "Civil / infrastructure",
  "Telecommunications",
  "Other",
];

const DURATIONS = ["Less than 1 day", "1-3 days", "4-7 days", "1-2 weeks", "2-4 weeks", "More than 1 month"];
const STATES = ["NSW", "VIC", "QLD", "WA", "SA", "TAS", "NT", "ACT"];

const HIERARCHY_COLOURS = {
  eliminate: "#065f46", substitute: "#0d9488", isolate: "#1d4ed8",
  engineer: "#1e3a8a", admin: "#d97706", ppe: "#b91c1c",
};

function LegalNoticeBanner() {
  return (
    <div className="bg-warning/20 border-2 border-ink p-3 text-xs leading-relaxed" data-testid="swms-legal-notice">
      <strong className="block label-eyebrow text-ink mb-1">LEGAL NOTICE</strong>
      A SWMS generated by SafeTradie must be reviewed and tailored to your specific site before work
      commences. A generic SWMS does not meet legal requirements unless reviewed on site and amended
      for actual hazards, layout, weather, equipment and workers.
      <strong> Work must stop immediately if HRCW is not being carried out in accordance with this SWMS.</strong>
    </div>
  );
}

export default function SwmsGenerator() {
  const { swms_id } = useParams();
  const nav = useNavigate();
  const [ref, setRef] = useState(null);
  const [workersRoster, setWorkersRoster] = useState([]);
  const [step, setStep] = useState(0);
  const [saving, setSaving] = useState(false);
  const [busyAi, setBusyAi] = useState(false);
  const [form, setForm] = useState({
    company_name: "", abn: "", business_address: "", business_phone: "",
    business_email: "", work_activity: "", site_location: "", site_state: "NSW",
    site_type: "", start_date: "", duration: "",
    works_manager_name: "", works_manager_phone: "",
    has_principal_contractor: false, pc_business: "", pc_contact: "",
    pc_phone: "", pc_swms_date: "",
    trade: "electrician", activity: "",
    workers: [],
    hrcw_codes: [],
    rows: [],
    compliance_responsible: "", compliance_measures: "",
    review_responsible: "", review_measures: "",
    review_date: "", consulted_workers: [], hsr_name: "",
    plant: [], ppe: [], training: [],
    emergency_contact: "", nearest_hospital: "", assembly_point: "",
    first_aider: "",
  });

  // Load reference data + profile + workers
  useEffect(() => {
    (async () => {
      try {
        const [refRes, profRes, wRes] = await Promise.all([
          api.get("/swms/reference"),
          api.get("/auth/me").catch(() => ({ data: {} })),
          api.get("/workers").catch(() => ({ data: [] })),
        ]);
        setRef(refRes.data);
        setWorkersRoster(wRes.data || []);
        // Auto-fill business from profile
        const p = profRes.data || {};
        setForm((f) => ({
          ...f,
          company_name: f.company_name || p.company_name || "",
          business_phone: f.business_phone || p.phone || "",
          business_email: f.business_email || p.email || "",
        }));
      } catch (e) {
        toast.error("Failed to load reference data");
      }
    })();
  }, []);

  // Load existing SWMS if editing
  useEffect(() => {
    if (!swms_id) return;
    api.get(`/swms/${swms_id}`).then((r) => {
      setForm((f) => ({ ...f, ...r.data }));
      setRef((cur) => cur); // keep reference
    }).catch(() => toast.error("Could not load SWMS"));
  }, [swms_id]);

  const patch = (k, v) => setForm((f) => ({ ...f, [k]: v }));
  const patchMany = (obj) => setForm((f) => ({ ...f, ...obj }));

  const tradeDef = ref?.trades?.[form.trade];
  const activities = tradeDef?.activities || [];

  // Compliance-measure defaults
  useEffect(() => {
    if (!form.compliance_measures && form.company_name) {
      patch("compliance_measures",
        `${form.company_name} WHS policies and procedures, general and site-specific induction training, ` +
        "toolbox talk before commencing HRCW, SWMS provided to and discussed with all workers before " +
        "work commences, ongoing supervision by experienced site supervisor.");
    }
    if (!form.review_measures) {
      patch("review_measures",
        "SWMS control measures will be reviewed and revised if necessary when: work tasks or methods " +
        "change; an unexpected hazard is identified; new information about a hazard becomes available; " +
        "a notifiable incident occurs; or control measures are found to be inadequate.");
    }
    // eslint-disable-next-line
  }, [form.company_name]);

  // When trade/activity changes, auto-suggest HRCW
  const suggestHrcw = async () => {
    try {
      const r = await api.post("/swms/ai/suggest-hrcw", { trade: form.trade, activity: form.activity });
      const codes = Array.from(new Set([...(form.hrcw_codes || []), ...(r.data?.hrcw_codes || [])]));
      patch("hrcw_codes", codes);
      toast.success(`${r.data?.hrcw_codes?.length || 0} HRCW categories pre-selected`);
    } catch {
      toast.error("HRCW suggestion failed");
    }
  };

  const suggestRows = async () => {
    setBusyAi(true);
    try {
      const r = await api.post("/swms/ai/suggest-rows", {
        trade: form.trade, activity: form.activity,
        hrcw_codes: form.hrcw_codes, site_state: form.site_state,
        rows: form.rows,
      });
      const newRows = r.data?.rows || [];
      patch("rows", [...(form.rows || []), ...newRows]);
      if (r.data?.fallback) {
        toast.warning("AI unavailable — using safe defaults. Please review and tailor.");
      } else {
        toast.success(`${newRows.length} task rows drafted`);
      }
    } catch (e) {
      toast.error("AI draft failed");
    }
    setBusyAi(false);
  };

  const save = async ({ navigate = false } = {}) => {
    setSaving(true);
    try {
      let res;
      if (form.swms_id) {
        res = await api.patch(`/swms/${form.swms_id}`, form);
      } else {
        res = await api.post("/swms", form);
      }
      setForm((f) => ({ ...f, ...res.data }));
      toast.success(`Saved — ${res.data.reference}`);
      if (navigate) nav("/dashboard/swms");
    } catch (e) {
      toast.error(e?.response?.data?.detail || "Save failed");
    }
    setSaving(false);
  };

  const next = () => setStep((s) => Math.min(STEPS.length - 1, s + 1));
  const prev = () => setStep((s) => Math.max(0, s - 1));

  // Step-specific content renderers
  const stepContent = () => {
    switch (STEPS[step].key) {
      case "business": return <StepBusiness form={form} patch={patch} />;
      case "trade": return <StepTrade form={form} patch={patch} ref={ref}
                                      workersRoster={workersRoster} onAfter={suggestHrcw} />;
      case "hrcw": return <StepHrcw form={form} patch={patch} ref={ref}
                                    onSuggest={suggestHrcw} />;
      case "rows": return <StepRows form={form} patch={patch} ref={ref}
                                    onAiSuggest={suggestRows} busyAi={busyAi}
                                    workersRoster={workersRoster} />;
      case "compliance": return <StepCompliance form={form} patch={patch} workersRoster={workersRoster} />;
      case "equipment": return <StepEquipment form={form} patch={patch} ref={ref} />;
      case "signoff": return <StepSignoff form={form} patch={patch} save={save}
                                          onDone={() => nav("/dashboard/swms")} />;
      default: return null;
    }
  };

  if (!ref) return <div className="p-8 text-sm text-muted-foreground">Loading reference data…</div>;

  return (
    <div className="space-y-4" data-testid="swms-generator">
      <div className="border-b-2 border-ink pb-3 flex items-end justify-between flex-wrap gap-2">
        <div>
          <div className="label-eyebrow">/ Documents · SWMS Generator</div>
          <h1 className="font-display text-3xl md:text-4xl font-black tracking-tighter mt-1">
            {form.swms_id ? `Edit ${form.reference}` : "New SWMS"}
          </h1>
        </div>
        <div className="flex gap-2">
          <Button variant="outline" className="btn-sharp border-ink" onClick={() => save()} disabled={saving} data-testid="swms-save">
            <FloppyDisk className="mr-2" />{saving ? "Saving…" : "Save draft"}
          </Button>
        </div>
      </div>

      <LegalNoticeBanner />

      <div className="grid grid-cols-12 gap-4">
        {/* LEFT — Wizard (7 cols) */}
        <div className="col-span-12 lg:col-span-7 bg-background border border-border p-4">
          <div className="flex flex-wrap gap-1 mb-4 border-b border-border pb-3">
            {STEPS.map((s, i) => (
              <button
                key={s.key}
                onClick={() => setStep(i)}
                className={`text-[10px] px-2 py-1 font-bold tracking-widest ${i === step ? "bg-ink text-warning" : "bg-muted text-ink hover:bg-warning"}`}
                data-testid={`swms-step-${i}`}
              >
                {s.label}
              </button>
            ))}
          </div>
          <div className="min-h-[50vh]">{stepContent()}</div>
          <div className="flex justify-between mt-6 pt-4 border-t border-border gap-2">
            <Button variant="outline" className="btn-sharp border-ink" onClick={prev} disabled={step === 0} data-testid="swms-prev">
              <ArrowLeft className="mr-2" />Back
            </Button>
            {step < STEPS.length - 1 ? (
              <Button className="btn-sharp bg-ink text-white hover:bg-authority" onClick={next} data-testid="swms-next">
                Next <ArrowRight className="ml-2" />
              </Button>
            ) : (
              <Button className="btn-sharp bg-warning text-ink hover:bg-yellow-400" onClick={() => save({ navigate: false })} data-testid="swms-finish">
                Finish <CheckCircle className="ml-2" weight="fill" />
              </Button>
            )}
          </div>
        </div>

        {/* RIGHT — Live Preview (5 cols) */}
        <div className="col-span-12 lg:col-span-5">
          <div className="sticky top-4">
            <div className="label-eyebrow mb-2">Live preview</div>
            <SwmsPreview doc={form} hrcwCatalog={ref.hrcw_categories} />
          </div>
        </div>
      </div>
    </div>
  );
}

