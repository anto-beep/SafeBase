function StepSignoff({ form, patch, save, onDone }) {
  const [sigWorker, setSigWorker] = useState("");
  const [sigText, setSigText] = useState("");
  const [busy, setBusy] = useState(false);

  const signInPerson = async () => {
    if (!form.swms_id) { toast.error("Save the SWMS first"); return; }
    if (!sigWorker) { toast.error("Select worker"); return; }
    if (!sigText) { toast.error("Type initials or full name as signature"); return; }
    setBusy(true);
    try {
      await api.post(`/swms/${form.swms_id}/sign`, {
        name: sigWorker, signature_data: sigText, signed_via: "in_person",
      });
      const updated = await api.get(`/swms/${form.swms_id}`);
      patch("workers", updated.data.workers);
      patch("status", updated.data.status);
      toast.success(`${sigWorker} signed`);
      setSigWorker(""); setSigText("");
    } catch { toast.error("Sign failed"); }
    setBusy(false);
  };

  const sendSmsLinks = async () => {
    if (!form.swms_id) { toast.error("Save the SWMS first"); return; }
    try {
      const r = await api.post(`/swms/${form.swms_id}/send-sign-links`);
      toast.success(`${r.data.sent} sign link${r.data.sent === 1 ? "" : "s"} generated (SMS delivery MOCKED — see Alerts for tokens)`);
    } catch { toast.error("Failed to generate links"); }
  };

  const downloadPdf = () => {
    if (!form.swms_id) { toast.error("Save the SWMS first"); return; }
    const token = localStorage.getItem("st_token");
    const backend = process.env.REACT_APP_BACKEND_URL;
    fetch(`${backend}/api/swms/${form.swms_id}/pdf`, { headers: { Authorization: `Bearer ${token}` } })
      .then((r) => r.blob()).then((b) => {
        const url = URL.createObjectURL(b);
        const a = document.createElement("a");
        a.href = url; a.download = `${form.reference || "swms"}.pdf`; a.click();
        URL.revokeObjectURL(url);
        toast.success("PDF downloaded");
      }).catch(() => toast.error("PDF download failed"));
  };

  return (
    <Section title="Generate and sign" hint="Save, download the PDF, and collect worker sign-offs." testid="swms-step-signoff">
      <div className="bg-ink text-white p-4">
        <div className="label-eyebrow text-warning">Status</div>
        <div className="font-display text-2xl font-black tracking-tighter mt-1">{(form.status || "draft").toUpperCase().replace("_", " ")}</div>
        <div className="text-xs text-white/60 mt-1">{form.reference || "Save to assign reference"}</div>
      </div>

      <div className="grid grid-cols-1 md:grid-cols-3 gap-3 mt-3">
        <Button className="btn-sharp bg-warning text-ink hover:bg-yellow-400 h-14" onClick={() => save()} disabled={busy} data-testid="swms-signoff-save">
          <FloppyDisk className="mr-2" weight="fill" />Save
        </Button>
        <Button variant="outline" className="btn-sharp border-ink h-14" onClick={downloadPdf} data-testid="swms-signoff-pdf">
          <FilePdf className="mr-2" weight="fill" />Download PDF
        </Button>
        <Button variant="outline" className="btn-sharp border-ink h-14" onClick={sendSmsLinks} data-testid="swms-signoff-sms">
          <PaperPlaneTilt className="mr-2" weight="fill" />Send SMS sign links
        </Button>
      </div>

      <div className="border-2 border-ink p-4 mt-4 space-y-3">
        <div className="font-display font-black text-lg">In-person sign-off</div>
        <div className="grid grid-cols-1 md:grid-cols-3 gap-3">
          <div>
            <Label className="label-eyebrow">Worker</Label>
            <Select value={sigWorker} onValueChange={setSigWorker}>
              <SelectTrigger className="h-10 rounded-none border-ink mt-1" data-testid="swms-sig-worker"><SelectValue placeholder="Select…" /></SelectTrigger>
              <SelectContent>{form.workers.filter((w) => !w.signed).map((w) => <SelectItem key={w.name} value={w.name}>{w.name}</SelectItem>)}</SelectContent>
            </Select>
          </div>
          <div className="md:col-span-2">
            <Label className="label-eyebrow">Type signature (full name or initials)</Label>
            <Input value={sigText} onChange={(e) => setSigText(e.target.value)} className="h-10 rounded-none border-ink mt-1" data-testid="swms-sig-input" />
          </div>
        </div>
        <Button className="btn-sharp bg-ink text-white hover:bg-authority" onClick={signInPerson} disabled={busy} data-testid="swms-sig-submit">
          <Hand className="mr-2" weight="fill" />Sign
        </Button>
      </div>

      {form.workers?.length > 0 && (
        <div className="border border-border mt-3">
          <div className="label-eyebrow p-3 border-b border-border">Sign-off status</div>
          <div className="divide-y divide-border" data-testid="swms-signed-status">
            {form.workers.map((w) => (
              <div key={w.name} className="flex items-center justify-between p-3 text-sm">
                <span className="font-bold">{w.name}</span>
                {w.signed ? (
                  <span className="text-emerald-700 flex items-center gap-2 text-xs font-bold tracking-widest">
                    <CheckCircle weight="fill" /> SIGNED · {w.signed_at?.slice(0, 10)} · {w.signed_via?.toUpperCase()}
                  </span>
                ) : (
                  <span className="text-amber-600 text-xs font-bold tracking-widest">AWAITING</span>
                )}
              </div>
            ))}
          </div>
        </div>
      )}
    </Section>
  );
}
